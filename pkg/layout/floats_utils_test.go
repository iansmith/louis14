// LOU-497: float fragmentation. Blink slices a float across fragmentainers
// like any other block: PositionFloat lays it out with the fragmentainer,
// keeps its break token (a parallel flow), and the float resumes from that
// token in the next fragmentainer (floats_utils.cc:242-452,
// block_layout_algorithm.cc:1722-1822 @
// a9f50e522efa9005e6ec765a9a785c74f5c2c86b).

// layoutMulticolForFloatTest lays out mc as a multicol container 100px
// wide (two columns, no gap unless styles say otherwise).
func layoutMulticolForFloatTest(t *testing.T, mc *html.Node, styles map[*html.Node]*css.Style) *LayoutResult {
	t.Helper()
	wdm := WritingDirectionMode{WritingModeHorizontalTB, DirectionLTR}
	space := NewConstraintSpaceBuilder(wdm, wdm, true).
		SetAvailableSize(LogicalSize{InlineSize: 100, BlockSize: Indefinite}).
		SetPercentageResolutionSize(LogicalSize{InlineSize: 100, BlockSize: Indefinite}).
		Build()
	result := NewMulticolLayoutAlgorithm(testContext(), buildTestTree(mc, styles), space).Layout()
	if result == nil || result.Fragment == nil {
		t.Fatal("layout returned nil")
	}
	t.Cleanup(func() {
		if t.Failed() {
			dumpFragmentTree(t, "", result.Fragment)
		}
	})
	return result
}

// columnChildren returns the column fragments of a multicol result, with
// their offsets.
func columnChildren(result *LayoutResult) []ChildLink {
	var cols []ChildLink
	for _, ch := range result.Fragment.Children {
		if ch.Fragment.BoxType == BoxTypeColumn {
			cols = append(cols, ch)
		}
	}
	return cols
}

// fragmentsOfNode returns the direct children of frag generated by node.
func fragmentsOfNode(frag *PhysicalFragment, node *html.Node) []ChildLink {
	var out []ChildLink
	for _, ch := range frag.Children {
		if ch.Fragment != nil && ch.Fragment.Node == node {
			out = append(out, ch)
		}
	}
	return out
}

// Mirrors css-multicol/float-and-block: a 200px float beside a 200px block
// in a balanced two-column multicol. The float breaks at the 100px column
// end and resumes at the top of the second column, covering the block
// there too.
func TestFloatFragmentation_FloatSlicedAcrossColumns(t *testing.T) {
	float := makeNode("div")
	block := makeNode("div")
	mc := makeNode("div", float, block)
	styles := map[*html.Node]*css.Style{
		mc:    makeStyle("display", "block", "column-count", "2", "column-gap", "0"),
		float: makeStyle("display", "block", "float", "left", "width", "50px", "height", "200px"),
		block: makeStyle("display", "block", "height", "200px"),
	}
	result := layoutMulticolForFloatTest(t, mc, styles)
	cols := columnChildren(result)
	if len(cols) != 2 {
		t.Fatalf("columns = %d, want 2", len(cols))
	}
	for i, col := range cols {
		if h := col.Fragment.Size.HeightF64(); h != 100 {
			t.Errorf("column %d height = %v, want 100", i, h)
		}
		frags := fragmentsOfNode(col.Fragment, float)
		if len(frags) != 1 {
			t.Fatalf("column %d: float fragments = %d, want 1", i, len(frags))
		}
		f := frags[0]
		if top, h := f.Offset.Top.Float64(), f.Fragment.Size.HeightF64(); top != 0 || h != 100 {
			t.Errorf("column %d: float fragment top=%v height=%v, want 0, 100", i, top, h)
		}
	}
}

// Mirrors css-multicol/spanner-in-child-after-parallel-flow-001: a float
// that breaks inside (a parallel flow) holds back a column spanner nested
// in the following block until the float has finished, so the spanner sits
// below the balanced 90px column row.
func TestFloatFragmentation_SpannerAfterParallelFlow(t *testing.T) {
	float := makeNode("div")
	spanner := makeNode("div")
	wrapper := makeNode("div", spanner)
	mc := makeNode("div", float, wrapper)
	styles := map[*html.Node]*css.Style{
		mc: makeStyle("display", "block", "column-count", "2", "column-gap", "0",
			"orphans", "1", "widows", "1"),
		float:   makeStyle("display", "block", "float", "left", "width", "50px", "height", "180px"),
		wrapper: makeStyle("display", "block"),
		spanner: makeStyle("display", "block", "column-span", "all", "height", "10px"),
	}
	result := layoutMulticolForFloatTest(t, mc, styles)
	if h := result.Fragment.Size.HeightF64(); h != 100 {
		t.Errorf("multicol height = %v, want 100", h)
	}
	var spannerTop float64 = -1
	for _, ch := range result.Fragment.Children {
		if ch.Fragment.Node == spanner {
			spannerTop = ch.Offset.Top.Float64()
		}
	}
	if spannerTop != 90 {
		t.Errorf("spanner top = %v, want 90", spannerTop)
	}
	// The float resumes at the top of the second column of the row above
	// the spanner. (louis14 gives the wrapper's empty remainder after the
	// spanner a row of its own; that row is not under test here.)
	var cols []ChildLink
	for _, col := range columnChildren(result) {
		if col.Offset.Top.Float64() < spannerTop {
			cols = append(cols, col)
		}
	}
	if len(cols) != 2 {
		t.Fatalf("columns above the spanner = %d, want 2", len(cols))
	}
	for i, col := range cols {
		frags := fragmentsOfNode(col.Fragment, float)
		if len(frags) != 1 || frags[0].Offset.Top.Float64() != 0 ||
			frags[0].Fragment.Size.HeightF64() != 90 {
			t.Errorf("column %d: float fragments = %v, want one 90px at top 0", i, frags)
		}
	}
}

// Mirrors css-multicol/multicol-fill-balance-038: a monolithic float whose
// block-start margin edge is above the fragmentainer start. Its margins are
// unbreakable (BlockSizeForFragmentation adds them for a float laid out
// without fragmentation, fragmentation_utils.cc:1562-1570), but the part
// before the fragmentainer start does not count: PositionFloat measures the
// unbreakable block-size from the margin edge (floats_utils.cc:434-445).
// The column row is 100px: -30 + 40 (margin) + 20 + 70 (margin).
func TestFloatFragmentation_MonolithicFloatMarginsAboveFragmentainerStart(t *testing.T) {
	empty := makeNode("div")
	float := makeNode("div")
	mc := makeNode("div", empty, float)
	styles := map[*html.Node]*css.Style{
		mc: makeStyle("display", "block", "column-count", "2", "line-height", "20px",
			"orphans", "1", "widows", "1"),
		empty: makeStyle("display", "block", "margin-bottom", "-30px"),
		float: makeStyle("display", "block", "float", "left", "width", "1px", "contain", "size",
			"height", "20px", "margin-top", "40px", "margin-bottom", "70px"),
	}
	result := layoutMulticolForFloatTest(t, mc, styles)
	if h := result.Fragment.Size.HeightF64(); h != 100 {
		t.Errorf("multicol height = %v, want 100", h)
	}
}

// A monolithic float that does not fit below earlier content is pushed to
// the next column (a break before it, in a parallel flow), while a later
// in-flow sibling that fits stays in the first column (floats_utils.cc:
// 349-389 and :402-418; block_layout_algorithm.cc:1792-1800).
func TestFloatFragmentation_BreakBeforeMonolithicFloat(t *testing.T) {
	first := makeNode("div")
	float := makeNode("div")
	last := makeNode("div")
	mc := makeNode("div", first, float, last)
	styles := map[*html.Node]*css.Style{
		mc: makeStyle("display", "block", "column-count", "2", "column-gap", "0",
			"column-fill", "auto", "height", "100px"),
		first: makeStyle("display", "block", "height", "60px"),
		float: makeStyle("display", "block", "float", "left", "width", "50px", "contain", "size",
			"height", "80px"),
		last: makeStyle("display", "block", "height", "20px"),
	}
	result := layoutMulticolForFloatTest(t, mc, styles)
	cols := columnChildren(result)
	if len(cols) != 2 {
		t.Fatalf("columns = %d, want 2", len(cols))
	}
	if n := len(fragmentsOfNode(cols[0].Fragment, float)); n != 0 {
		t.Errorf("column 0: float fragments = %d, want 0 (pushed)", n)
	}
	lasts := fragmentsOfNode(cols[0].Fragment, last)
	if len(lasts) != 1 || lasts[0].Offset.Top.Float64() != 60 {
		t.Errorf("column 0: last block fragments = %v, want one at top 60", lasts)
	}
	floats := fragmentsOfNode(cols[1].Fragment, float)
	if len(floats) != 1 || floats[0].Offset.Top.Float64() != 0 ||
		floats[0].Fragment.Size.HeightF64() != 80 {
		t.Errorf("column 1: float fragments = %v, want one 80px at top 0", floats)
	}
}

// ExclusionSpace records floats that broke before or inside, mirroring
// Blink's has_break_{before,inside}_{left,right}_float_ bits and their
// queries (exclusion_space.h:135-193 @ a9f50e522efa).
func TestExclusionSpace_FragmentainerBreakFlags(t *testing.T) {
	wdm := WritingDirectionMode{WritingModeHorizontalTB, DirectionLTR}
	es := (&ExclusionSpace{}).Add(Exclusion{BlockSize: 10, InlineSize: 10})
	if es.HasFragmentainerBreak() || es.NeedsBreakBeforeFloat(css.ClearNone, wdm) {
		t.Fatal("fresh exclusion space reports a fragmentainer break")
	}

	inside := es.SetHasBreakInsideFloat(ExclusionInlineStart)
	if es.HasFragmentainerBreak() {
		t.Error("SetHasBreakInsideFloat mutated the receiver")
	}
	if !inside.HasFragmentainerBreak() {
		t.Error("break inside a float: HasFragmentainerBreak = false")
	}
	if !inside.NeedsClearancePastFragmentainer(css.ClearLeft, wdm) ||
		!inside.NeedsClearancePastFragmentainer(css.ClearBoth, wdm) {
		t.Error("clear:left/both past a left float broken inside must clear past the fragmentainer")
	}
	if inside.NeedsClearancePastFragmentainer(css.ClearRight, wdm) {
		t.Error("clear:right must not clear past a left float")
	}
	if inside.NeedsBreakBeforeFloat(css.ClearNone, wdm) {
		t.Error("a float broken inside does not push later uncleared floats")
	}
	// Flags survive Add.
	if !inside.Add(Exclusion{}).HasFragmentainerBreak() {
		t.Error("Add dropped the fragmentainer break flags")
	}

	before := es.SetHasBreakBeforeFloat(ExclusionInlineEnd)
	if !before.NeedsBreakBeforeFloat(css.ClearNone, wdm) {
		t.Error("a float pushed to the next fragmentainer pushes every later float")
	}
	if !before.NeedsClearancePastFragmentainer(css.ClearRight, wdm) {
		t.Error("clear:right past a pushed right float must clear past the fragmentainer")
	}
}

// The free BlockSizeForFragmentation adds a float's margins when the float
// was laid out without block fragmentation (Blink's kIndefiniteSize case,
// fragmentation_utils.cc:1562-1570 @ a9f50e522efa), and only then.
func TestBlockSizeForFragmentation_FloatMargins(t *testing.T) {
	wdm := WritingDirectionMode{WritingModeHorizontalTB, DirectionLTR}
	frag := &PhysicalFragment{
		Size:       geometry.PhysicalSizeFromF64Round(10, 20),
		IsFloating: true,
		BoxData:    &PhysicalBoxData{Margin: PhysicalEdges{Top: 40, Bottom: 70}},
	}
	if got := BlockSizeForFragmentation(wdm, &LayoutResult{Fragment: frag}); got != 130 {
		t.Errorf("unfragmented float: BlockSizeForFragmentation = %v, want 130", got)
	}
	fragmented := &LayoutResult{Fragment: frag, BlockSizeForFragmentation: 20, HasBlockSizeForFragmentation: true}
	if got := BlockSizeForFragmentation(wdm, fragmented); got != 20 {
		t.Errorf("fragmented float: BlockSizeForFragmentation = %v, want 20", got)
	}
	notFloat := &PhysicalFragment{Size: frag.Size, BoxData: frag.BoxData}
	if got := BlockSizeForFragmentation(wdm, &LayoutResult{Fragment: notFloat}); got != 20 {
		t.Errorf("in-flow box: BlockSizeForFragmentation = %v, want 20", got)
	}
}

// LOU-502: a float of an inline formatting context fragments like one in a
// block flow. LineBreaker::HandleFloat positions it through PositionFloat
// with the fragmentation space; a float that breaks inside becomes a
// parallel-flow break token of the inline formatting context
// (InlineBreakToken::CreateForParallelBlockFlow), resumed first in the next
// fragmentainer (LineBreaker::NextLine), inline/line_breaker.cc:893-912,
// :3727-3842 @ a9f50e522efa9005e6ec765a9a785c74f5c2c86b.
func inlineFloatMulticolStyles(mc, float *html.Node) map[*html.Node]*css.Style {
	return map[*html.Node]*css.Style{
		mc: makeStyle("display", "block", "column-count", "2", "column-gap", "0",
			"column-fill", "auto", "height", "100px", "font-family", "Ahem", "font-size", "10px",
			"line-height", "10px", "orphans", "1", "widows", "1"),
		float: makeStyle("display", "block", "float", "left", "width", "20px", "height", "200px"),
	}
}

// One line beside a 200px float: the lines finish in the first column, the
